import jsPDF from 'jspdf';
import 'jspdf-autotable';

export const generateCIOMSPDF = (caseData) => {
  const doc = new jsPDF();
  
  // Header
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('CIOMS I EXPEDITED REPORT', 105, 20, { align: 'center' });
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text('Generated by Vigithink Pharmacovigilance System', 105, 28, { align: 'center' });
  
  // Box 1: Administrative
  doc.setFont('helvetica', 'bold');
  doc.text('ADMINISTRATIVE INFORMATION', 14, 40);
  doc.setFont('helvetica', 'normal');
  doc.text(`Case Number: ${caseData.caseNumber || 'N/A'}`, 14, 48);
  doc.text(`Initial Receipt Date: ${caseData.companyReceivedDate ? new Date(caseData.companyReceivedDate).toLocaleDateString() : 'N/A'}`, 14, 54);
  doc.text(`Country of Incidence: ${caseData.country || 'N/A'}`, 14, 60);
  doc.text(`Report Type: ${caseData.reportType || 'N/A'}`, 100, 48);
  doc.text(`Priority: ${caseData.priority || 'N/A'}`, 100, 54);
  doc.text(`Expedited: ${caseData.expeditedReporting === 'Yes' ? 'Yes' : 'No'}`, 100, 60);
  
  // I. REACTION INFORMATION
  doc.setFont('helvetica', 'bold');
  doc.text('I. REACTION INFORMATION', 14, 75);
  doc.setFont('helvetica', 'normal');
  doc.text(`Patient Initials: ${caseData.patient?.initials || 'Unknown'}`, 14, 83);
  doc.text(`Date of Birth: ${caseData.patient?.dob || 'Unknown'}`, 14, 89);
  doc.text(`Gender: ${caseData.patient?.gender || 'Unknown'}`, 14, 95);
  doc.text(`Weight: ${caseData.patient?.weight || 'Unknown'} kg`, 100, 83);
  doc.text(`Height: ${caseData.patient?.height || 'Unknown'} cm`, 100, 89);
  doc.text(`Pregnancy: ${caseData.patient?.pregnancy || 'No'}`, 100, 95);

  // Events Table
  const eventRows = (caseData.events || []).map(ev => [
    ev.descriptionAsReported || '',
    ev.coding?.pt || '',
    ev.onsetDate || '',
    ev.outcome || '',
    ev.seriousness || ''
  ]);
  
  doc.autoTable({
    startY: 105,
    head: [['Reported Term', 'MedDRA PT', 'Onset Date', 'Outcome', 'Seriousness']],
    body: eventRows,
    theme: 'grid',
    styles: { fontSize: 8 },
    headStyles: { fillColor: [51, 65, 85] }
  });

  // II. SUSPECT DRUG(S) INFORMATION
  doc.setFont('helvetica', 'bold');
  let finalY = doc.lastAutoTable.finalY || 105;
  doc.text('II. SUSPECT DRUG(S) INFORMATION', 14, finalY + 15);
  
  const drugRows = (caseData.products || []).filter(p => p.type === 'Suspect').map(prod => [
    prod.tradeName || '',
    prod.genericName || '',
    prod.actionTaken || 'Unknown',
    prod.dechallenge || 'Unknown',
    prod.rechallenge || 'Unknown'
  ]);

  doc.autoTable({
    startY: finalY + 20,
    head: [['Trade Name', 'Generic Name', 'Action Taken', 'Dechallenge', 'Rechallenge']],
    body: drugRows.length > 0 ? drugRows : [['No suspect drugs reported', '', '', '', '']],
    theme: 'grid',
    styles: { fontSize: 8 },
    headStyles: { fillColor: [51, 65, 85] }
  });

  // III. NARRATIVE
  finalY = doc.lastAutoTable.finalY || 150;
  doc.setFont('helvetica', 'bold');
  doc.text('III. CASE NARRATIVE & CLINICAL COURSE', 14, finalY + 15);
  
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  const narrative = caseData.analysis?.narrative || 'No narrative provided.';
  const splitTitle = doc.splitTextToSize(narrative, 180);
  doc.text(splitTitle, 14, finalY + 23);

  // Footer
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text(`Page ${i} of ${pageCount}`, 196, 285, { align: 'right' });
    doc.text(`Vigithink System - Confidential CIOMS Document`, 14, 285);
  }

  // Save PDF
  doc.save(`CIOMS_${caseData.caseNumber || 'Report'}.pdf`);
};
